// Generates public/firebase-messaging-sw.js with the Firebase web config inlined.
// The static export copies public/ verbatim (no Next.js env processing), so the
// service worker config must be baked in at build time. Reads NEXT_PUBLIC_FIREBASE_*
// from the environment, falling back to .env.local / .env for local dev.
// Run automatically on postinstall and before build/dev (see package.json).
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// Minimal .env loader (NEXT_PUBLIC_* only); real env always wins.
function loadEnvFile(path) {
  if (!existsSync(path)) return;
  for (const line of readFileSync(path, 'utf8').split(/\r?\n/)) {
    const m = /^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)\s*$/.exec(line);
    if (!m) continue;
    const [, key, raw] = m;
    if (key.startsWith('NEXT_PUBLIC_') && process.env[key] === undefined) {
      let value = raw;
      if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
        value = value.slice(1, -1);
      }
      process.env[key] = value;
    }
  }
}
loadEnvFile(join(root, '.env.local'));
loadEnvFile(join(root, '.env'));

const firebaseConfig = {
  apiKey: process.env.NEXT_PUBLIC_FIREBASE_API_KEY ?? '',
  authDomain: process.env.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN ?? '',
  projectId: process.env.NEXT_PUBLIC_FIREBASE_PROJECT_ID ?? '',
  messagingSenderId: process.env.NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID ?? '',
  appId: process.env.NEXT_PUBLIC_FIREBASE_APP_ID ?? '',
};

const configured = Boolean(firebaseConfig.apiKey && firebaseConfig.projectId);
if (!configured) {
  console.warn(
    '[gen-firebase-sw] NEXT_PUBLIC_FIREBASE_* not set — writing a placeholder service worker (push disabled until configured).'
  );
}

const sw = `// AUTO-GENERATED by scripts/gen-firebase-sw.mjs — do not edit by hand.
// Firebase Cloud Messaging background handler (web/PWA). Config is inlined at build time.
importScripts('https://www.gstatic.com/firebasejs/10.12.2/firebase-app-compat.js');
importScripts('https://www.gstatic.com/firebasejs/10.12.2/firebase-messaging-compat.js');

firebase.initializeApp(${JSON.stringify(firebaseConfig, null, 2)});

const messaging = firebase.messaging();

messaging.onBackgroundMessage((payload) => {
  const title = (payload && payload.notification && payload.notification.title) || 'Notification';
  const options = {
    body: (payload && payload.notification && payload.notification.body) || '',
    data: (payload && payload.data) || {},
  };
  self.registration.showNotification(title, options);
});
`;

mkdirSync(join(root, 'public'), { recursive: true });
writeFileSync(join(root, 'public', 'firebase-messaging-sw.js'), sw, 'utf8');
console.log(`firebase-messaging-sw.js generated (${configured ? 'configured' : 'placeholder'}).`);
